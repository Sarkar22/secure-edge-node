/*
 * node_top.sv -- Secure edge-inference node (SIMON-CTR, latency-hidden crypto).
 * --------------------------------------------------------------------------
 * One small FPGA datapath that classifies a 2-D feature with a 2-8-1 MLP and
 * encrypts the telemetry record before transmission, as a streaming CTR endpoint:
 *
 *   (x0,x1) --[MVM]--> z1 --[CORDIC tanh]--> a1 --[MVM]--> z2 --[CORDIC sigmoid]-->
 *            (prob,class) --[pack 128b record]--.
 *                                                XOR --> ciphertext
 *   counter(nonce||seq) --[SIMON128/128]--> keystream ---'
 *
 * CO-DESIGN / novelty: in CTR mode the keystream = SIMON(counter) depends only on
 * the counter, NOT on the inference result, so SIMON is launched at accept time and
 * runs CONCURRENTLY with the MVM/CORDIC. By the time the record is ready the keystream
 * is waiting, and encryption is a single-cycle 128-bit XOR -> the block-cipher latency
 * is HIDDEN behind the inference. Adding confidentiality costs ~0 DSP (activation and
 * cipher are DSP-free; the MVM holds the only DSP) and ~0 extra latency.
 *
 * Weights, SIMON key, and CTR nonce come from node_consts.svh (generated by
 * model/node_model.py) so the node is bit-exact to the golden model.
 */
`timescale 1ns/1ps
module node_top #(
    parameter bit HIDE_CRYPTO = 1   // 1 = latency-hidden CTR (default); 0 = blocking
) (
    input  logic               clk,
    input  logic               rst,
    input  logic signed [13:0] i_x0,    // Q2.12 feature
    input  logic signed [13:0] i_x1,    // Q2.12 feature
    input  logic [31:0]        i_seq,   // record sequence (CTR counter low bits)
    input  logic               i_valid, // start one inference+encrypt
    output logic               o_ready, // node idle (can accept)
    output logic [127:0]       o_ct,    // ciphertext (transmit with seq)
    output logic signed [13:0] o_prob,  // probability  (Q2.12, telemetry/debug)
    output logic               o_class, // predicted class
    output logic               o_valid, // result valid
    input  logic               i_ready  // consumer ready
);
    `include "node_consts.svh"

    localparam int NIN_L1 = 2;

    typedef enum logic [3:0] {
        S_IDLE, S_L1MAC, S_L1ACT, S_L2MAC, S_L2ACT, S_PACK, S_ENC, S_FIN, S_DONE
    } st_t;
    st_t st;

    // ---- datapath registers ----
    logic signed [FX_W-1:0] xreg  [0:1];
    logic [31:0]            seqreg;
    logic signed [FX_W-1:0] z1buf [0:HID-1];
    logic signed [FX_W-1:0] a1buf [0:HID-1];
    logic signed [FX_W-1:0] z2reg, probreg;
    logic                   classreg;
    logic [127:0]           recreg, ksreg, ctreg;
    logic                   ks_have;

    logic [3:0] no, ni, fed, got;
    logic signed [ACCW-1:0] acc;

    // ---- shared MAC (one signed multiplier => one DSP) ----
    logic signed [FX_W-1:0] macA;
    logic signed [WW-1:0]   macW;
    wire  [4:0] w1idx = ni*HID + no;          // valid in L1 (ni<=1, no<=7) => <=15
    always_comb begin
        if (st == S_L1MAC) begin macA = xreg[ni[0]];  macW = W1[w1idx[3:0]]; end
        else               begin macA = a1buf[ni];    macW = W2[ni[2:0]];    end
    end
    wire signed [FX_W+WW-1:0] prod = macA * macW;     // 32-bit signed product
    wire signed [ACCW-1:0]    accN = acc + prod;      // prod sign-extended

    // round Q.(2*WF) -> Q2.12 (half-up) and saturate to the activation's range
    function automatic logic signed [FX_W-1:0] finalize
            (input logic signed [ACCW-1:0] a, input logic is_sig);
        logic signed [ACCW-1:0] sh, lo, hi, rnd;
        begin
            rnd = 1 <<< (WF-1);                 // signed +2048 (round half up)
            sh  = (a + rnd) >>> WF;             // Q.(2*WF) -> Q2.12, arithmetic
            lo  = is_sig ? SIG_LO : TANH_LO;
            hi  = is_sig ? SIG_HI : TANH_HI;
            if      (sh < lo) finalize = lo[FX_W-1:0];
            else if (sh > hi) finalize = hi[FX_W-1:0];
            else              finalize = sh[FX_W-1:0];
        end
    endfunction

    // ---- CORDIC activation unit (zero DSP), time-shared by both layers ----
    logic               a_ivalid, a_imode;
    logic signed [13:0] a_ix;
    wire                a_ovalid;
    wire  [13:0]        a_ofx;
    always_comb begin
        a_ivalid = 1'b0; a_imode = 1'b0; a_ix = '0;
        if (st == S_L1ACT) begin a_imode = 1'b0; a_ix = z1buf[fed]; a_ivalid = (fed < HID[3:0]); end
        if (st == S_L2ACT) begin a_imode = 1'b1; a_ix = z2reg;      a_ivalid = (fed < 4'd1);     end
    end
    cordic_activation u_act (
        .clk(clk), .rst(rst), .i_x(a_ix), .i_mode(a_imode), .i_valid(a_ivalid),
        .o_ready(), .o_fx(a_ofx), .o_valid(a_ovalid), .i_ready(1'b1));

    // ---- SIMON128/128 keystream generator (zero DSP/BRAM), launched CONCURRENTLY ----
    // CTR: encrypt the counter (nonce||seq); result is XORed with the record later.
    wire [31:0]  ctr_seq  = (st == S_IDLE) ? i_seq : seqreg;
    logic        e_ivalid;
    wire         e_oready, e_ovalid;
    wire [255:0] e_oct;
    // HIDE_CRYPTO=1: launch at accept (concurrent with inference -> hidden).
    // HIDE_CRYPTO=0: launch only after the record is packed (serial -> blocking).
    assign e_ivalid = HIDE_CRYPTO ? ((st == S_IDLE) && i_valid)
                                  : ((st == S_ENC)  && e_oready);
    simon_enc #(.UNROLL(1)) u_enc (
        .clk(clk), .rst(rst),
        .i_key  ({128'b0, NODE_KEY}),
        .i_block({128'b0, CTR_NONCE, ctr_seq}),       // counter block (low 128b)
        .i_valid(e_ivalid), .o_ready(e_oready),
        .o_ct(e_oct), .o_valid(e_ovalid), .i_ready(1'b1));

    assign o_ready = (st == S_IDLE);
    assign o_ct    = ctreg;
    assign o_prob  = probreg;
    assign o_class = classreg;
    assign o_valid = (st == S_DONE);

    integer k;
    always_ff @(posedge clk) begin
        if (rst) begin
            st <= S_IDLE; no <= '0; ni <= '0; fed <= '0; got <= '0; acc <= '0;
            classreg <= 1'b0; probreg <= '0; z2reg <= '0; ctreg <= '0;
            recreg <= '0; ksreg <= '0; ks_have <= 1'b0; seqreg <= '0;
            for (k = 0; k < 2;   k++) xreg[k]  <= '0;
            for (k = 0; k < HID; k++) begin z1buf[k] <= '0; a1buf[k] <= '0; end
        end else begin
            // concurrent keystream capture (SIMON runs alongside the inference)
            if (e_ovalid) begin ksreg <= e_oct[127:0]; ks_have <= 1'b1; end
            case (st)
            // ----------------------------------------------------------------
            S_IDLE: if (i_valid) begin
                xreg[0] <= i_x0; xreg[1] <= i_x1; seqreg <= i_seq;
                no <= '0; ni <= '0; acc <= $signed(B1[0]);
                ks_have <= 1'b0;                    // arm for this record's keystream
                st <= S_L1MAC;
            end
            // ---- layer-1 MVM: 8 neurons x 2 inputs, one product/cycle -------
            S_L1MAC: begin
                if (ni == NIN_L1-1) begin
                    z1buf[no] <= finalize(accN, 1'b0);          // tanh range
                    if (no == HID-1) begin
                        st <= S_L1ACT; fed <= '0; got <= '0;
                    end else begin
                        no <= no + 1; ni <= '0; acc <= $signed(B1[no+1]);
                    end
                end else begin
                    ni <= ni + 1; acc <= accN;
                end
            end
            // ---- stream z1[0..7] through CORDIC (tanh), collect a1 ----------
            S_L1ACT: begin
                if (a_ivalid)  fed <= fed + 1;
                if (a_ovalid) begin a1buf[got] <= $signed(a_ofx); got <= got + 1; end
                if (got == HID[3:0]) begin
                    st <= S_L2MAC; ni <= '0; acc <= $signed(B2);
                end
            end
            // ---- layer-2 MVM: 1 neuron x 8 inputs --------------------------
            S_L2MAC: begin
                if (ni == HID-1) begin
                    z2reg <= finalize(accN, 1'b1);              // sigmoid range
                    st <= S_L2ACT; fed <= '0; got <= '0;
                end else begin
                    ni <= ni + 1; acc <= accN;
                end
            end
            // ---- one sigmoid through CORDIC -> prob, class ------------------
            S_L2ACT: begin
                if (a_ivalid) fed <= fed + 1;
                if (a_ovalid) begin
                    probreg  <= $signed(a_ofx);
                    classreg <= ($signed(a_ofx) >= $signed(14'(1 << (FX_F-1))));
                    st <= S_PACK;
                end
            end
            // ---- pack the 128-bit telemetry record -------------------------
            S_PACK: begin
                recreg <= {53'b0, seqreg, classreg, probreg, xreg[1], xreg[0]};
                st <= HIDE_CRYPTO ? S_FIN : S_ENC;
            end
            // ---- blocking mode only: launch SIMON here, then wait ----------
            S_ENC: if (e_oready) st <= S_FIN;
            // ---- CTR encryption = single-cycle XOR (keystream already ready) -
            S_FIN: if (ks_have) begin ctreg <= recreg ^ ksreg; st <= S_DONE; end
            // ---- present result --------------------------------------------
            S_DONE: if (i_ready) st <= S_IDLE;
            default: st <= S_IDLE;
            endcase
        end
    end
endmodule
