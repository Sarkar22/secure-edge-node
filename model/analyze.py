#!/usr/bin/env python3
"""
Derive the paper's budget numbers, tables (paper/tables.tex), and figures
(results/figures/) for the secure edge-inference node.

Inputs (all measured, nothing hand-typed):
  results/node_synth.csv                          node P&R (synth_node.tcl)
  results/synth/utilization_hier.rpt              per-block decomposition (constants below)
  ../cordic-activation/results/baseline_synth.csv DSP polynomial tanh, same part
  ../simon-cipher/results/aes_synth.csv           pipelined AES-128, same part
  tb/node_lat_tb.sv                               measured latency (constants below)

Figures follow the shared style: categorical slots blue/orange/aqua (validated
palette), entity->hue fixed across all figures (inference/CORDIC=blue, MVM=orange,
cipher=aqua), ink-colored text, no in-figure titles (captions live in LaTeX).
"""
import csv, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOLO = os.path.dirname(ROOT)

def read_csv1(path):
    with open(path) as f:
        return list(csv.DictReader(f))[0]

# ---- totals from place&route ----
row   = read_csv1(os.path.join(ROOT, "results", "node_synth.csv"))
LUT   = int(row["lut"]);  FF = int(row["ff"]);  DSP = int(row["dsp"])
BRAM  = int(row["bram"]); FMAX = float(row["fmax_mhz"]); POWER = float(row["power_w"])

# ---- baselines measured on the SAME part (sibling projects) ----
poly = read_csv1(os.path.join(SOLO, "cordic-activation", "results", "baseline_synth.csv"))
aes  = read_csv1(os.path.join(SOLO, "simon-cipher",      "results", "aes_synth.csv"))

# ---- per-block decomposition (results/synth/utilization_hier.rpt) ----
#      name, LUT, FF, DSP  (FFs sum to the flat total; LUT sum differs slightly
#      from the flat total due to cross-hierarchy LUT combining -- caption notes it)
BLOCKS = [
    ("CORDIC activation", 1646, 1813, 0),
    ("MVM + control",      305,  704, 1),
    ("SIMON cipher",       225,  268, 0),
]
LUT_ACT, LUT_MVM, LUT_ENC = BLOCKS[0][1], BLOCKS[1][1], BLOCKS[2][1]
FF_MVM = BLOCKS[1][2]

# ---- measured latency (tb/node_lat_tb.sv) ----
LAT_HIDDEN, LAT_BLOCK = 111, 181
CIPHER_CYC = LAT_BLOCK - LAT_HIDDEN            # = SIMON U=1 block latency (70)

# ---- accuracy (model/node_model.py self-check) ----
NODE_ACC, IDEAL_ACC, FLOAT_ACC = 94.58, 94.58, 97.08

# ---- power split (results/synth/power.rpt: vectorless post-route estimate) ----
POWER_DYN = 0.162          # design dynamic; remainder (0.289 W) is device static

# ---- conventional-stack estimate: same-part component sums (clearly labeled est.) --
CONV_LUT = int(poly["lut"]) + LUT_MVM + int(aes["lut"])
CONV_FF  = int(poly["ff"])  + FF_MVM  + int(aes["ff"])
CONV_DSP = int(poly["dsp"]) + 1 + int(aes["dsp"])
CONV_BRAM= int(poly["bram"]) + int(aes["bram"])

# ---------------------------------------------------------------- budget ------
fmax_hz   = FMAX * 1e6
inf_per_s = fmax_hz / LAT_HIDDEN
lat_us    = LAT_HIDDEN / fmax_hz * 1e6
tput_mbps = inf_per_s * 128 / 1e6              # encrypted telemetry bits/s
energy_nj = POWER / inf_per_s * 1e9            # J per secured inference (total power)
energy_dyn_nj = POWER_DYN / inf_per_s * 1e9    # dynamic-only share

print(f"node: {LUT} LUT, {FF} FF, {DSP} DSP, {BRAM} BRAM, {FMAX:.1f} MHz, {POWER} W")
print(f"accuracy {NODE_ACC}% (= ideal fixed-point); latency hidden {LAT_HIDDEN} vs "
      f"blocking {LAT_BLOCK} cyc ({CIPHER_CYC} hidden)")
print(f"throughput {inf_per_s/1e3:.0f}k secured inferences/s ({tput_mbps:.0f} Mb/s), "
      f"{lat_us:.2f} us/inf, {energy_nj:.0f} nJ/inf")
print(f"conventional stack estimate: {CONV_LUT} LUT, {CONV_FF} FF, {CONV_DSP} DSP "
      f"({CONV_LUT/LUT:.1f}x LUT, {CONV_DSP}x DSP)")

# ------------------------------------------------------------- tables.tex -----
T = []
T.append(r"% AUTO-GENERATED by model/analyze.py")
# Table I: node summary + budget
T.append(r"""\begin{table}[tb]\centering\setlength{\tabcolsep}{5pt}\footnotesize
\caption{Secure edge-inference node: implementation (KV260, post-P\&R) and end-to-end
budget.}
\label{tab:node}
\begin{tabular}{lr}
\toprule
metric & value\\\midrule
LUT / FF & %d / %d\\
DSP / BRAM & \textbf{%d} / %d\\
$F_{\max}$ & %.1f\,MHz\\
power (vectorless est.) & %.3f\,W (%.3f\,W dynamic)\\
task accuracy & %.2f\%% (= ideal fixed-pt; float %.2f\%%)\\
latency (hidden crypto) & %d cyc (%.2f\,$\mu$s)\\
throughput & %.2f\,M inf/s (%.0f\,Mb/s enc.)\\
energy & %.0f\,nJ/inf (%.0f\,nJ dynamic)\\
verification & 244/244 bit-exact (stream)\\
\bottomrule\end{tabular}\end{table}""" % (
    LUT, FF, DSP, BRAM, FMAX, POWER, POWER_DYN, NODE_ACC, FLOAT_ACC,
    LAT_HIDDEN, lat_us, inf_per_s/1e6, tput_mbps, energy_nj, energy_dyn_nj))
# Table II: resource decomposition
rows = "".join(
    r"%s & %d & %d & %s\\" % (n, l, f, (r"\textbf{%d}" % d if d else "0")) + "\n"
    for (n, l, f, d) in BLOCKS)
T.append(r"""\begin{table}[tb]\centering\setlength{\tabcolsep}{5pt}\footnotesize
\caption{Resource decomposition (hierarchical report; post-combining site counts,
totaling 2174). The activation and the cipher are DSP-free; the sole DSP is the MVM
MAC. The cipher is %.0f\%% of the node LUTs. The flat total (%d) counts LUT
\emph{cells}: a combined dual-output LUT occupies one site but counts as two cells
(see Sec.~\ref{sec:results}).}
\label{tab:decomp}
\begin{tabular}{lrrr}
\toprule
block & LUT & FF & DSP\\\midrule
%s\bottomrule\end{tabular}\end{table}""" % (100.0*LUT_ENC/(LUT_ACT+LUT_MVM+LUT_ENC), LUT, rows))
# Table III: latency hiding
T.append(r"""\begin{table}[tb]\centering\setlength{\tabcolsep}{6pt}\footnotesize
\caption{Latency-hiding via CTR keystream precomputation (same RTL, \texttt{HIDE\_CRYPTO}
parameter). Both schedules emit identical ciphertext.}
\label{tab:latency}
\begin{tabular}{lr}
\toprule
crypto scheduling & latency (cyc)\\\midrule
serial (encrypt after inference) & %d\\
co-designed (CTR, concurrent) & %d\\
\midrule
cipher latency removed & %d (%.1f\%%)\\
\bottomrule\end{tabular}\end{table}""" % (
    LAT_BLOCK, LAT_HIDDEN, CIPHER_CYC, 100.0*CIPHER_CYC/LAT_BLOCK))
# Table IV: vs conventional alternatives, all measured on the same part
T.append(r"""\begin{table}[tb]\centering\setlength{\tabcolsep}{2.8pt}\footnotesize
\caption{This work vs.\ conventional alternatives, each measured on the same device
(KV260, P\&R). The conventional-node row is an \emph{estimated} component sum
(integration overhead excluded). The AES-128 row is a fully pipelined,
throughput-class engine, an upper bound for the conventional cipher; the polynomial
unit is \texttt{tanh}-only (the node also needs sigmoid).}
\label{tab:vs}
\begin{tabular}{llrrrr}
\toprule
role & design & LUT & FF & DSP & BRAM\\
\midrule
activation & CORDIC \texttt{tanh}+$\sigma$ (used) & %d & %d & \textbf{0} & 0\\
           & DSP poly.\ \texttt{tanh} & %d & %d & 12 & 0\\
\midrule
cipher & SIMON-CTR (used, hidden) & %d & %d & \textbf{0} & 0\\
       & AES-128 (pipelined) & %d & %d & %d & %d\\
\midrule
node & \textbf{this work (measured)} & \textbf{%d} & \textbf{%d} & \textbf{1} & \textbf{0}\\
     & conventional (est.\ sum) & $\approx$%d & $\approx$%d & 13 & %d\\
\bottomrule\end{tabular}\end{table}""" % (
    LUT_ACT, BLOCKS[0][2], int(poly["lut"]), int(poly["ff"]),
    LUT_ENC, BLOCKS[2][2], int(aes["lut"]), int(aes["ff"]), int(aes["dsp"]), int(aes["bram"]),
    LUT, FF, CONV_LUT, CONV_FF, CONV_BRAM))
open(os.path.join(ROOT, "paper", "tables.tex"), "w").write("\n".join(T) + "\n")
print("wrote paper/tables.tex (4 tables)")

# --------------------------------------------------------------- figures ------
try:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
except Exception:
    print("matplotlib not available -> skipped figures "
          "(run with /tmp/mplvenv/bin/python)")
    raise SystemExit

FIG = os.path.join(ROOT, "results", "figures")
os.makedirs(FIG, exist_ok=True)

# validated categorical palette (slots 1-3) + ink/chrome roles
C_BLUE, C_ORANGE, C_AQUA = "#2a78d6", "#eb6834", "#1baf7a"   # inference/CORDIC, MVM, cipher
INK, INK2, MUTED, GRID, BASE = "#0b0b0b", "#52514e", "#898781", "#e1e0d9", "#c3c2b7"
plt.rcParams.update({
    "font.size": 7.5, "axes.edgecolor": BASE, "axes.linewidth": 0.6,
    "xtick.color": MUTED, "ytick.color": MUTED, "text.color": INK,
    "axes.labelcolor": INK2, "figure.facecolor": "white", "axes.facecolor": "white",
})

def strip(ax, keep_x=True):
    for s in ("top", "right", "left"):
        ax.spines[s].set_visible(False)
    if not keep_x:
        ax.spines["bottom"].set_visible(False)

# ---------------- Fig 1: architecture / dataflow diagram -----------------------
# NOT generated here: fig_arch is authored in TikZ (paper/fig_arch.tex) for
# publication quality. Compile it separately (tectonic/pdflatex) and copy the PDF to
# results/figures/fig_arch.pdf. This script must NOT overwrite it.

# ---------------- Fig 2: latency Gantt (serial vs co-designed) -----------------
fig, ax = plt.subplots(figsize=(3.5, 1.75))
BH = 0.34
# serial row (top): one timeline, two segments with a 2px-equivalent gap
ax.barh(2.0, LAT_HIDDEN, height=BH, color=C_BLUE, ec="white", lw=1.2)
ax.barh(2.0, CIPHER_CYC, left=LAT_HIDDEN, height=BH, color=C_AQUA, ec="white", lw=1.2)
ax.text(LAT_HIDDEN/2, 2.0+BH/2+0.10, "inference", ha="center", va="bottom",
        fontsize=6.4, color=INK2)
ax.text(LAT_HIDDEN+CIPHER_CYC/2, 2.0+BH/2+0.10, "SIMON", ha="center", va="bottom",
        fontsize=6.4, color=INK2)
# co-designed rows (bottom): two separate lanes, no overlap
ax.barh(0.95, LAT_HIDDEN, height=BH, color=C_BLUE, ec="white", lw=1.2)
ax.text(LAT_HIDDEN/2, 0.95+BH/2+0.10, "inference", ha="center", va="bottom",
        fontsize=6.4, color=INK2)
ax.barh(0.38, CIPHER_CYC, height=BH*0.8, color=C_AQUA, ec="white", lw=1.2)
ax.text(CIPHER_CYC+2.5, 0.38, "SIMON (concurrent)", ha="left", va="center",
        fontsize=6.0, color=INK2)
# reference lines + saving annotation
ax.axvline(LAT_HIDDEN, color=BASE, lw=0.7, ls=(0, (3, 2)), zorder=0)
ax.axvline(LAT_BLOCK,  color=BASE, lw=0.7, ls=(0, (3, 2)), zorder=0)
ax.annotate("", xy=(LAT_BLOCK, 1.55), xytext=(LAT_HIDDEN, 1.55),
            arrowprops=dict(arrowstyle="<->", color=INK, lw=0.8))
ax.text((LAT_HIDDEN+LAT_BLOCK)/2, 1.63, f"−{CIPHER_CYC} cyc "
        f"({100.0*CIPHER_CYC/LAT_BLOCK:.0f}%)", ha="center", va="bottom",
        fontsize=6.4, color=INK, fontweight="bold")
ax.set_yticks([2.0, 0.7]); ax.set_yticklabels(["serial", "co-designed\n(hidden)"],
                                              fontsize=6.8, color=INK)
ax.set_xlabel("cycles", fontsize=7)
ax.set_xlim(0, 196); ax.set_ylim(-0.05, 2.75)
ax.set_xticks([0, 50, LAT_HIDDEN, 150, LAT_BLOCK])
ax.set_xticklabels(["0", "50", str(LAT_HIDDEN), "150", str(LAT_BLOCK)],
                   fontsize=6.4)
strip(ax); ax.tick_params(length=0)
for ext in ("pdf", "png"):
    fig.savefig(os.path.join(FIG, f"fig_latency.{ext}"), bbox_inches="tight", dpi=300)
plt.close(fig)

# ---------------- Fig 3: node vs conventional stack (same-part measurements) ----
fig, ax = plt.subplots(figsize=(3.5, 1.55))
def stack(y, parts, colors):
    left = 0
    for v, c in zip(parts, colors):
        # no white edge on very thin segments -- the edge would paint them over
        lw = 1.2 if v >= 150 else 0
        ax.barh(y, v, left=left, height=0.5, color=c, ec="white", lw=lw)
        left += v
    return left
t1 = stack(1.0, [LUT_ACT, LUT_MVM, LUT_ENC], [C_BLUE, C_ORANGE, C_AQUA])
t2 = stack(0.0, [int(poly["lut"]), LUT_MVM, int(aes["lut"])], [C_BLUE, C_ORANGE, C_AQUA])
# annotate with the flat P&R totals used throughout the paper (the stacked
# segments are the hierarchical attribution; caption notes the combining delta)
ax.text(t1 + 150, 1.0, f"{LUT:,} LUT · 1 DSP", va="center", fontsize=6.8,
        color=INK, fontweight="bold")
ax.text(t2 + 150, 0.0, f"≈{CONV_LUT:,} LUT · 13 DSP", va="center", fontsize=6.8,
        color=INK)
ax.set_yticks([1.0, 0.0])
ax.set_yticklabels(["this work\n(measured)", "conventional\n(est. sum)"],
                   fontsize=6.8, color=INK)
ax.set_xlabel("LUTs", fontsize=7)
ax.set_xlim(0, 14800); ax.set_ylim(-0.55, 1.55)
ax.set_xticks([0, 2500, 5000, 7500, 10000])
ax.set_xticklabels(["0", "2,500", "5,000", "7,500", "10,000"], fontsize=6.4)
strip(ax); ax.tick_params(length=0)
# legend: three chips, one row, below the plot
handles = [plt.Rectangle((0, 0), 1, 1, fc=c, ec="none")
           for c in (C_BLUE, C_ORANGE, C_AQUA)]
ax.legend(handles,
          ["activation (CORDIC | poly-tanh)", "MVM", "cipher (SIMON | AES-128)"],
          loc="upper center", bbox_to_anchor=(0.5, -0.42), ncol=3,
          fontsize=6.4, frameon=False, handlelength=1.0, handleheight=0.9,
          columnspacing=0.8, handletextpad=0.45)
for ext in ("pdf", "png"):
    fig.savefig(os.path.join(FIG, f"fig_compare.{ext}"), bbox_inches="tight", dpi=300)
plt.close(fig)

# retire the old decomposition figure (replaced by fig_compare + Table II)
for ext in ("pdf", "png"):
    old = os.path.join(FIG, f"fig_decomp.{ext}")
    if os.path.exists(old): os.remove(old)

print("wrote results/figures/fig_arch, fig_latency, fig_compare (.pdf/.png)")
